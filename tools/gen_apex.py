#!/usr/bin/env python3
"""Generates apps/ix3_themes/hud/layouts/apex.json (the Apex theme): two big dials
(speed left, revs right) with thin inner arcs, a huge gear between them with a shift strip,
boost and two readout slots under it. Edit this and regenerate; do not hand-edit the JSON."""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'apps', 'ix3_themes', 'hud', 'layouts', 'apex.json')
MIN = os.path.join(ROOT, 'apps', 'ix3_themes', 'hud', 'layouts', 'hybrid.json')     # its bottom row (strip_*) is the shared one

CY = 318                     # dials' centre y (content area is 1920x660)
DIAL = 580                   # outer dial layer size
CXL, CXR = 400, 1520         # dial centres


def text(i, x, y, w, h, t, font, color='fg', align='center', **kw):
    d = {'id': i, 'type': 'text', 'z': 5, 'x': x, 'y': y, 'w': w, 'h': h, 'text': t, 'font': font, 'color': color, 'align': align}
    d.update(kw)
    return d


def arc(i, cx, size, sig, mn, mx, width, color, start=225, sweep=270, **kw):
    d = {'id': i, 'type': 'arc', 'class': 'content', 'z': 2, 'x': cx - size // 2, 'y': CY - size // 2, 'w': size, 'h': size,
         'signal': sig, 'min': mn, 'max': mx, 'width': width, 'color': color, 'start': start, 'sweep': sweep}
    d.update(kw)
    return d


W = [{'id': 'bg', 'type': 'fill', 'class': 'content', 'z': 0, 'x': 0, 'y': 0, 'w': 1920, 'h': 660, 'color': 'bg'}]
# speed dial (left, fills clockwise from the lower left), rev dial (right, mirrored: fills anticlockwise from the lower right)
W.append(arc('speed_arc', CXL, DIAL, 'speed', 0, 300, 26, 'fg'))
W.append(arc('rev_arc', CXR, DIAL, 'rpm', 0, 8000, 26, 'accent', start=135, sweep=-270))
# thin inner arcs: fuel inside the speed dial, coolant inside the rev dial
W.append(arc('fuel_arc', CXL, 470, 'fuel', 0, 1, 8, 'dim', conn=2))
W.append(arc('cool_arc', CXR, 470, 'coolant', 40, 130, 8, 'dim', start=135, sweep=-270, conn=2))
# inside the dials
W.append(text('speed', CXL - 190, CY - 112, 380, 192, '{{speed}}', 'n_speed'))
W.append(text('speed_unit', CXL - 100, CY + 88, 200, 36, '{{u:speedLc}}', 'n_unit', 'dim'))
W.append(text('rpm', CXR - 190, CY - 62, 380, 60, '{{rpm}}', 'y_val'))
W.append(text('rpm_unit', CXR - 100, CY + 12, 200, 36, 'rpm', 'n_unit', 'dim'))
W.append(text('fuel_lbl', CXL - 110, CY + 150, 220, 30, 'FUEL {{fuelPct}}%', 'r_label', 'dim'))
W.append(text('cool_lbl', CXR - 110, CY + 150, 220, 30, 'WATER {{coolant}}°', 'r_label', 'dim'))
# the bottom gaps of the dials: oil left, mode right
W.append(text('oil', CXL - 120, CY + 252, 240, 30, 'OIL {{oil}}°', 'r_label', 'dim'))
# centre column
W.append(text('badge', 810, 36, 300, 34, '{{badge}}', 'badge', 'dim'))
W.append(text('mode', 810, 96, 300, 27, '{{mode}}', 'head', 'accent', spacing=2))
W.append(text('gear', 810, 132, 300, 222, '{{gearnum}}', 'y_gear', hotWhen='now'))
W.append({'id': 'shift_strip', 'type': 'meter', 'class': 'content', 'z': 2, 'x': 740, 'y': 392, 'w': 440, 'h': 16,
          'signal': 'rpm', 'min': 0, 'max': 7000, 'segments': 28, 'gap': 4, 'colors': ['fg', 'accent', 'hot'], 'at': [0.6, 0.86], 'conn': 2})
W.append(text('boost_head', 740, 440, 200, 27, 'BOOST {{u:boost}}', 'head', 'accent', 'left', spacing=1, toggle='showBoost'))
W.append(text('boost', 900, 428, 280, 45, '{{boost}}', 'small', 'fg', 'right', toggle='showBoost'))
W.append({'id': 'boost_bar', 'type': 'meter', 'class': 'content', 'z': 2, 'x': 740, 'y': 482, 'w': 440, 'h': 10,
          'signal': 'boost', 'min': 0, 'max': 1.6, 'segments': 24, 'gap': 4, 'colors': ['fg', 'accent', 'hot'], 'at': [0.5, 0.9],
          'peak': 3000, 'toggle': 'showBoost', 'conn': 2})
for n, y in ((1, 530), (2, 586)):
    W.append(text('slot%d_head' % n, 740, y + 10, 150, 27, '{{slotHeadU:%d}}' % n, 'head', 'accent', 'left', spacing=1))
    W.append(text('slot%d' % n, 880, y, 300, 45, '{{slot:%d}}{{slotSuffix:%d}}' % (n, n), 'small', 'fg', 'right', slot=str(n), fit=['unit']))
# the bottom row (clock, range, outside temperature) as Minimal draws it
for w in json.load(open(MIN))['widgets']:
    if w['id'].startswith('strip_'):
        W.append(w)

L = {'schemaVersion': 2, 'name': 'Apex', 'packWaste': 3, 'theme': 'apex',
     'slots': [{'id': '1', 'where': 'centre, row 1', 'default': 'power'}, {'id': '2', 'where': 'centre, row 2', 'default': 'torque'}],
     '_about': "Apex cluster, generated by tools/gen_apex.py (edit that and regenerate): two big dials, the speed on the left (white, filling clockwise) and the revs on the right (orange, filling the other way), a thin inner arc in each (fuel, coolant), the speed and the rpm inside them, a huge gear between with the drive mode over it, a segmented shift strip, boost with a peak-hold bar, and two readout slots. Full screen: the theme's own clock, range and outside temperature along the bottom, BMW's gear letter left uncovered. Black covers BMW's gauges. No map window. Widget reference: shared/hud.js header.",
     'widgets': W}
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    json.dump(L, f, indent=2, ensure_ascii=False)
    f.write('\n')
import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import badge_spot; badge_spot.apply(OUT)
print('apex.json:', len(W), 'widgets')
