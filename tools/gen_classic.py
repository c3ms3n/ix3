#!/usr/bin/env python3
"""Generates apps/ix3_themes/hud/layouts/classic.json (the Classic theme), after a photo of BMW's analog cluster at night
(apps/7.jpeg): two big round dials (speed 0..160 mph or 0..260 km/h on the left, revs 0..7 on the right) with red-orange ticks,
numbers, a tapered glowing needle and a hub, a small fuel dial on the far left and a small temperature dial on the far right,
the lit display between the dials with the time, range and outside temperature, and the gear letter under the rev dial.
Edit this and regenerate; do not hand-edit the JSON."""
import json, math, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUTS = {False: os.path.join(ROOT, 'apps', 'ix3_themes', 'hud', 'layouts', 'classic.json'),
        True: os.path.join(ROOT, 'apps', 'ix3_themes', 'hud', 'layouts', 'classic_map.json')}
FONT_DIR = os.path.join(ROOT, 'apps', 'ix3_themes', 'hud', 'fonts')

ABOUT = ("Classic cluster, generated by tools/gen_classic.py (edit that and regenerate), after a photo of BMW's analog cluster at night (apps/7.jpeg): the speed dial on the left (0..160 mph, 0..260 km/h) and the rev dial on the right (0..7, the redline at 6.5), red-orange ticks and numbers, a tapered glowing needle and a hub in each, a small fuel dial far left and a small temperature dial far right, the lit display between them with the time, range and outside temperature, the gear letter and drive mode under the rev dial, and the speed digitally inside the speed dial. Black covers BMW's gauges.")
TICK = [255, 72, 34]
NEEDLE = [255, 58, 26]
RED = [255, 28, 18]


def cell(font):
    return json.load(open(os.path.join(FONT_DIR, font + '.json')))['cellHeight']


def pos(center, radius, deg):
    a = math.radians(deg)
    return (center[0] + radius * math.sin(a), center[1] - radius * math.cos(a))


def text(i, c, w, font, t, color='accent', align='center', **kw):
    h = cell(font)
    x0 = c[0] - w / 2 if align == 'center' else (c[0] - w if align == 'right' else c[0])
    d = {'id': i, 'type': 'text', 'z': 5, 'x': round(x0), 'y': round(c[1] - h / 2), 'w': w, 'h': h, 'text': t, 'font': font,
         'color': color, 'align': align}
    d.update(kw)
    return d


def dial(i, center, radius, start, sweep, signal, mn, mx, majors, minors, tick, needle, hub, red=None, ring=0.62, bezel=12, **kw):
    s = int(2 * (radius + 4))
    d = {'id': i, 'type': 'adial', 'class': 'content', 'z': 2, 'x': round(center[0] - s / 2), 'y': round(center[1] - s / 2), 'w': s, 'h': s,
         'signal': signal, 'min': mn, 'max': mx, 'radius': radius, 'hub': hub, 'start': start, 'sweep': sweep,
         'majors': majors, 'minors': minors, 'tickLen': tick, 'needle': needle, 'redFrom': red,
         'tickColor': TICK, 'needleColor': NEEDLE, 'redColor': RED, 'faceColor': [8, 14, 34], 'faceEdge': [2, 4, 10],
         'ring': [ring, 1.2, bezel]}
    d.update(kw)
    return d




def build(map_variant):
    # the Classic Map variant: smaller dials and a big window in the middle for the Waze map
    R = 205.0 if map_variant else 285.0
    LC, RC = ((365.0, 330.0), (1555.0, 330.0)) if map_variant else ((500.0, 330.0), (1420.0, 330.0))
    SMALL_R = 62.0 if map_variant else 80.0
    FC, TC = ((70.0, 420.0), (1850.0, 420.0)) if map_variant else ((100.0, 372.0), (1820.0, 372.0))
    LABF = 'f_lab2' if map_variant else 'f_lab'
    k = R / 285.0
    W = [{'id': 'bg', 'type': 'fill', 'class': 'content', 'z': 0, 'x': 0, 'y': 0, 'w': 1920, 'h': 660, 'color': 'bg'}]
    if map_variant:        # while the Waze map shows inside the theme a big window opens between the dials
        W[0].update({'hole': [650, 60, 620, 500], 'holeWhen': 'mapUp', 'holeInset': 0, 'holeRadius': 36})
    hide = {'toggle': '!mapUp'} if map_variant else {}
    # the lit display between the dials
    W.append(dict({'id': 'panel', 'type': 'apanel', 'class': 'content', 'z': 1, 'x': 640 if map_variant else 780, 'y': 100, 'w': 640 if map_variant else 360, 'h': 330, 'rect': [660, 120, 600, 270] if map_variant else [800, 130, 320, 260], 'radius': 14,
              'top': [28, 6, 4], 'bottom': [255, 62, 22], 'ribs': [5, 0.55, 0.5, 0.35]}, **hide))
    # the speed dial: 0..160 mph, a major tick every 20 (0..260 km/h in km/h)
    SPEED_START, SPEED_SWEEP = 232.0, 265.0
    W.append(dial('spd', LC, R, SPEED_START, SPEED_SWEEP, 'speed', {'us': 0, 'metric': 0}, {'us': 257.5, 'metric': 260},
                  {'us': 8, 'metric': 13}, 3, [round(24 * k), round(12 * k)], [0.93, round(34 * k), round(11 * k), 6], round(26 * k), bezel=round(12 * k)))
    # the rev dial: 0..7, the redline at 6.5
    REV_START, REV_SWEEP = 231.0, 245.0
    W.append(dial('rev', RC, R, REV_START, REV_SWEEP, 'rpm', 0, 7000, 7, 4, [round(24 * k), round(12 * k)], [0.93, round(34 * k), round(11 * k), 6], round(26 * k), red=6.5 / 7.0, bezel=round(12 * k)))
    # the small dials: fuel (far left) and engine temperature (far right)
    W.append(dial('fuel_dial', FC, SMALL_R, 205.0, 150.0, 'fuel', 0, 1, 2, 4, [round(12 * SMALL_R / 80), round(7 * SMALL_R / 80)], [0.82, 10, 5, 3], 8, ring=0.7, bezel=6))
    W.append(dial('temp_dial', TC, SMALL_R, 205.0, 150.0, 'coolant', 50, 130, 2, 4, [round(12 * SMALL_R / 80), round(7 * SMALL_R / 80)], [0.82, 10, 5, 3], 8, ring=0.7, bezel=6))

    # ---- the numbers round the dials
    LAB_R = R - 12 * k - 24 * k - 34 * k
    for v in range(0, 161, 20):                                      # mph
        d = SPEED_START + SPEED_SWEEP * v / 160.0
        W.append(text('mph%d' % v, pos(LC, LAB_R, d), 90, LABF, str(v), 'accent', 'center', toggle='units=us'))
    for v in range(0, 261, 40):                                      # km/h (a number every second tick)
        d = SPEED_START + SPEED_SWEEP * v / 260.0
        W.append(text('kmh%d' % v, pos(LC, LAB_R, d), 90, LABF, str(v), 'accent', 'center', toggle='!units=us'))
    for v in range(0, 8):
        d = REV_START + REV_SWEEP * v / 7.0
        W.append(text('rpm%d' % v, pos(RC, LAB_R, d), 60, LABF, str(v), 'accent', 'center'))
    # ---- inside the dials
    W.append(text('speed', (LC[0], LC[1] - 118 * k), 140, 'f_big', '{{speed}}', 'accent', 'right'))
    W.append(text('speed_u', (LC[0] + 6, LC[1] - 108 * k), 80, 'f_small', '{{u:speedLc}}', 'accent', 'left'))
    W.append(text('rpm_u', (RC[0], RC[1] - 118 * k), 200, 'f_small', '1/min x 1000', 'accent', 'center'))
    W.append(text('stage', (RC[0], RC[1] + (120 if map_variant else 190)), 70, 'f_gear', '{{stage}}', 'fg', 'center'))
    W.append(text('mode', (RC[0], RC[1] + (160 if map_variant else 232)), 220, 'f_small', '{{mode}}', 'accent', 'center'))
    # the small dials' labels
    W.append(text('fuel_1', (FC[0] - 38 * SMALL_R / 80, FC[1] - 52 * SMALL_R / 80), 40, 'f_small', '1', 'accent', 'center'))
    W.append(text('fuel_0', (FC[0] + 56 * SMALL_R / 80, FC[1] + 18 * SMALL_R / 80), 40, 'f_small', '0', 'accent', 'center'))
    W.append(text('temp_c', (TC[0] - 56 * SMALL_R / 80, TC[1] + 18 * SMALL_R / 80), 40, 'f_small', 'C', 'accent', 'center'))
    W.append(text('temp_h', (TC[0] + 40 * SMALL_R / 80, TC[1] - 52 * SMALL_R / 80), 40, 'f_small', 'H', 'accent', 'center'))
    # ---- the readouts under the lit window: time, range, outside temperature (warm white on black, like the photo)
    W.append(text('d_time', (960.0, 440.0), 260, 'f_disp', '{{time}} {{ampmLc}}', 'fg', 'center', **hide))
    W.append(text('d_range', (960.0, 492.0), 260, 'f_disp', '{{range}} {{u:distLc}}', 'fg', 'center', **hide))
    W.append(text('d_temp_h', (905.0, 544.0), 90, 'f_small', 'Temp', 'accent', 'center', **hide))
    W.append(text('d_temp', (1020.0, 544.0), 150, 'f_disp', '{{ambient}}{{u:temp}}', 'fg', 'center', **hide))
    W.append({'id': 'd_fuel_icon', 'type': 'icon', 'icon': 'fuel', 'z': 5, 'x': 806, 'y': 476, 'w': 26, 'h': 30, 'color': 'accent', **hide})
    # the bottom row
    W += [
        {'id': 'strip_cover_l', 'type': 'fill', 'class': 'content', 'z': 0, 'x': 0, 'y': 660, 'w': 1380, 'h': 60, 'color': 'bg', 'stripRow': 'l'},
        {'id': 'strip_cover_r', 'type': 'fill', 'class': 'content', 'z': 0, 'x': 1460, 'y': 660, 'w': 460, 'h': 60, 'color': 'bg', 'stripRow': 'r'},
        text('strip_time', (268.0, 690.0), 130, 'f_disp', '{{time}}', 'accent', 'right', stripRow='l'),
        text('strip_ampm', (278.0, 692.0), 50, 'f_small', '{{ampmLc}}', 'accent', 'left', stripRow='l'),
        text('strip_range', (960.0, 690.0), 110, 'f_disp', '{{range}}', 'accent', 'right', stripRow='l'),
        text('strip_range_u', (970.0, 692.0), 40, 'f_small', '{{u:distLc}}', 'accent', 'left', stripRow='l'),
        text('strip_out', (1745.0, 690.0), 100, 'f_disp', '{{ambient}}', 'accent', 'right', stripRow='r'),
        text('strip_out_u', (1755.0, 692.0), 40, 'f_small', '{{u:temp}}', 'accent', 'left', stripRow='r'),
    ]
    L = {'schemaVersion': 2, 'name': 'Classic Map' if map_variant else 'Classic', 'theme': 'classic', 'packWaste': 3,
         '_about': ABOUT + (" While the Waze map shows inside the theme a big window opens between the smaller dials (the lit display and its readouts give way)." if map_variant else " No map window.") + " Widget reference: shared/hud.js header.",
     'widgets': W}

    return L


for variant, path in OUTS.items():
    L = build(variant)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(L, f, indent=2, ensure_ascii=False)
        f.write('\n')
    import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import badge_spot; badge_spot.apply(path)
    print(os.path.basename(path), len(L['widgets']), 'widgets')
